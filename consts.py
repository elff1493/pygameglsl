
from OpenGL.GL import *
from OpenGL.GL.shaders import *

from enum import Enum


class Filter(Enum):
    LINEAR = GL_LINEAR
    NEAREST = GL_NEAREST


class MipMapFilter:
    LINEAR_LINEAR = GL_LINEAR_MIPMAP_LINEAR
    LINEAR_NEAREST = GL_LINEAR_MIPMAP_NEAREST
    NEAREST_LINEAR = GL_NEAREST_MIPMAP_LINEAR
    NEAREST_NEAREST = GL_NEAREST_MIPMAP_NEAREST


class Primitive(Enum):
    POINTS = GL_POINTS
    LINE_STRIPS = GL_LINE_STRIP
    LINE_LOOPS = GL_LINE_LOOP
    LINES = GL_LINES
    LINE_STRIP_ADJACENCY = GL_LINE_STRIP_ADJACENCY
    LINES_ADJACENCY = GL_LINES_ADJACENCY
    TRIANGLE_STRIP = GL_TRIANGLE_STRIP
    TRIANGLE_FAN = GL_TRIANGLE_FAN
    TRIANGLES = GL_TRIANGLES
    RIANGLE_STRIP_ADJACENCY = GL_TRIANGLE_STRIP_ADJACENCY
    TRIANGLES_ADJACENCY = GL_TRIANGLES_ADJACENCY
    PATCHES = GL_PATCHES